def _ask_default(prompt: str) -> str:
    return input(prompt)


def _yes(text: str) -> bool:
    return text.strip().lower() in {"y", "yes"}


def _is_git_repo(path: Path) -> bool:
    return (path / ".git").exists() or (
        subprocess.run(
            ["git", "-C", str(path), "rev-parse", "--is-inside-work-tree"],
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=30,
            shell=False,
            check=False,
        ).returncode
        == 0
    )


def _has_commit(path: Path) -> bool:
    proc = subprocess.run(
        ["git", "-C", str(path), "rev-parse", "HEAD"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=30,
        shell=False,
        check=False,
    )
    return proc.returncode == 0 and bool(proc.stdout.strip())


def _current_branch(repo: Path) -> str:
    current = subprocess.run(
        ["git", "-C", str(repo), "rev-parse", "--abbrev-ref", "HEAD"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=30,
        shell=False,
        check=False,
    )
    name = current.stdout.strip()
    if current.returncode == 0 and name and name != "HEAD":
        return name
    raise ValueError(f"{repo} has no current branch")


def default_branch(repo: Path) -> str:
    """origin/HEAD first, else current branch. Never assume demo-base."""
    symbolic = subprocess.run(
        ["git", "-C", str(repo), "symbolic-ref", "--quiet", "refs/remotes/origin/HEAD"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=30,
        shell=False,
        check=False,
    )
    if symbolic.returncode == 0:
        ref = symbolic.stdout.strip()
        if ref.startswith("refs/remotes/origin/"):
            return ref.removeprefix("refs/remotes/origin/")
    return _current_branch(repo)


def remote_slug(repo: Path) -> str | None:
    proc = subprocess.run(
        ["git", "-C", str(repo), "remote", "get-url", "origin"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=30,
        shell=False,
        check=False,
    )
    if proc.returncode != 0:
        return None
    return _slug_from_url(proc.stdout.strip())


def _slug_from_url(raw: str) -> str | None:
    text = raw.strip()
    if not text:
        return None
    if text.endswith(".git"):
        text = text[:-4]
    if text.startswith("git@"):
        _, _, rest = text.partition(":")
        parts = rest.split("/")
        if len(parts) >= 2:
            return f"{parts[-2]}/{parts[-1]}"
        return None
    parsed = urlparse(text)
    parts = [p for p in parsed.path.split("/") if p]
    if len(parts) >= 2:
        return f"{parts[-2]}/{parts[-1]}"
    if "/" in text and "://" not in text and not text.startswith("git@"):
        left, _, right = text.partition("/")
        if left and right and "/" not in right:
            return f"{left}/{right}"
    return None


def looks_like_slug(text: str) -> bool:
    parts = text.strip().split("/")
    return len(parts) == 2 and all(parts) and not Path(text).exists()


def validate_local_repo(path: Path) -> str | None:
    """None when ok. Otherwise a short error for the user."""
    if not path.exists():
        return f"{path} does not exist"
    if not _is_git_repo(path):
        return f"{path} is not a git repository"
    if not _has_commit(path):
        return f"{path} has no commits"
    return None


def _foreign_project(folder: Path) -> bool:
    if not folder.exists():
        return False
    if (folder / "treefleet.toml").is_file():
        return False
    for item in folder.iterdir():
        if item.name in {".", ".."}:
            continue
        return True
    return False


def _ensure_gitignore(folder: Path) -> str | None:
    if not _is_git_repo(folder):
        return None
    path = folder / ".gitignore"
    if path.is_file():
        text = path.read_text(encoding="utf-8")
        lines = {line.strip() for line in text.splitlines()}
        if ".env" in lines:
            return None
        suffix = "" if text.endswith("\n") or not text else "\n"
        path.write_text(text + suffix + ".env\n", encoding="utf-8")
        return "appended .env to .gitignore"
    path.write_text(".env\n", encoding="utf-8")
    return "wrote .gitignore with .env"


def _default_worktree() -> str:
    return r"C:\wt" if sys.platform == "win32" else "/tmp/tf-wt"


def _uv_lines() -> list[str]:
    return [
        'uv venv .venv-orch && uv pip install -p .venv-orch -e ".[orchestrator,dev]"',
        'uv venv .venv-worker && uv pip install -p .venv-worker -e ".[worker]"',
    ]


def _activate_hint() -> list[str]:
    if sys.platform == "win32":
        return [
            r"Then: .\.venv-orch\Scripts\activate   (or invoke .\.venv-orch\Scripts\treefleet.exe)",
        ]
    return [
        "Then: source .venv-orch/bin/activate   (or invoke .venv-orch/bin/treefleet)",
    ]


def _run_install(folder: Path) -> tuple[bool, str]:
    commands = [
        ["uv", "venv", ".venv-orch"],
        ["uv", "pip", "install", "-p", ".venv-orch", "-e", ".[orchestrator,dev]"],
        ["uv", "venv", ".venv-worker"],
        ["uv", "pip", "install", "-p", ".venv-worker", "-e", ".[worker]"],
    ]
    for command in commands:
        proc = subprocess.run(
            command,
            cwd=folder,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=600,
            shell=False,
            check=False,
        )
        if proc.returncode != 0:
            detail = (proc.stderr or proc.stdout or "install failed").strip().splitlines()
            last = detail[-1] if detail else "install failed"
            return False, f"install failed: {' '.join(command)} ({last[:200]})"
    return True, "install ok"


def _gh_default(args: list[str]) -> tuple[int, str, str]:
    proc = subprocess.run(
        ["gh", *args],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=60,
        shell=False,
        check=False,
    )
    return proc.returncode, proc.stdout or "", proc.stderr or ""


def _choose_pr(
    *,
    folder: Path,
    local_repo: Path | None,
    pr_repo: str | None,
    enable_pr: bool | None,
    yes: bool,
    ask: Ask,
    gh: Gh,
) -> dict[str, Any] | None:
    if enable_pr is False:
        return None
    if enable_pr is None:
        if yes:
            return None
        if not _yes(ask("Enable PR mode? [y/N] ")):
            return None
    code, _out, _err = gh(["auth", "status"])
    if code != 0:
        raise RuntimeError("gh is not authenticated; run gh auth login")
    code, login_out, _err = gh(["api", "user", "--jq", ".login"])
    login = login_out.strip()
    if code != 0 or not login or "/" in login:
        raise RuntimeError("gh is not authenticated; run gh auth login")
    slug = pr_repo
    if not slug and local_repo is not None:
        found = remote_slug(local_repo)
        if found:
            if yes or _yes(ask(f"Use {found} as pr.repo? [Y/n] ") or "y"):
                slug = found
    if not slug:
        if yes:
            raise RuntimeError("PR mode needs --pr-repo OWNER/NAME when --yes")
        typed = ask("GitHub owner/name for PRs: ").strip()
        if not looks_like_slug(typed) and "/" not in typed:
            raise RuntimeError("pr.repo must be owner/name")
        slug = typed if "/" in typed else ""
        if not slug:
            raise RuntimeError("pr.repo must be owner/name")
    base = "main"
    if local_repo is not None:
        try:
            base = default_branch(local_repo)
        except ValueError:
            base = "main"
    if not yes:
        typed_base = ask(f"PR base branch [{base}]: ").strip()
        if typed_base:
            base = typed_base
    return {
        "repo": slug,
        "base": base,
        "trusted": login,
    }


def _resolve_target(
    *,
    repo_flag: str | None,
    pr_repo_flag: str | None,
    yes: bool,
    ask: Ask,
) -> tuple[Path | None, str | None]:
    """Local path and/or owner/name slug from flags or the prompt."""
    if repo_flag:
        path = Path(repo_flag)
        err = validate_local_repo(path)
        if err:
            raise RuntimeError(err)
        return path.resolve(), pr_repo_flag
    if pr_repo_flag:
        if not looks_like_slug(pr_repo_flag) and "/" not in pr_repo_flag:
            raise RuntimeError("--pr-repo must be owner/name")
        return None, pr_repo_flag
    if yes:
        return None, None
    answer = ask("Which repo should TreeFleet work on? (local path or owner/name) ").strip()
    if not answer:
        return None, None
    if looks_like_slug(answer) or (answer.count("/") == 1 and not Path(answer).exists()):
        return None, answer
    path = Path(answer)
    err = validate_local_repo(path)
    if err:
        raise RuntimeError(err)
    return path.resolve(), None


def run_init(
    folder: Path,
    *,
    yes: bool = False,
    install: bool = False,
    repo: str | None = None,
    pr_repo: str | None = None,
    enable_pr: bool | None = None,
    worktree_root: str | None = None,
    ask: Ask | None = None,
    gh: Gh | None = None,
    run_install: Callable[[Path], tuple[bool, str]] | None = None,
) -> tuple[int, list[str]]:
    """Create onboarding files in folder. Never touches the target application repo's git state."""
    ask_fn = ask or _ask_default
    notes: list[str] = []
    try:
        folder.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        return 1, [f"could not create {folder}: {exc}"]

    toml_path = folder / "treefleet.toml"
    env_example = folder / ".env.example"
    if toml_path.is_file() or env_example.is_file():
        if toml_path.is_file():
            notes.append(f"left existing {toml_path.name}")
        if env_example.is_file():
            notes.append(f"left existing {env_example.name}")
        notes.append("already initialized; nothing overwritten")
        return 0, notes

    if _foreign_project(folder) and not yes:
        if not _yes(ask_fn(f"{folder} is not empty and has no treefleet.toml. Continue? [y/N] ")):
            return 1, ["write refused"]

    try:
        local_repo, slug = _resolve_target(repo_flag=repo, pr_repo_flag=pr_repo, yes=yes, ask=ask_fn)
    except RuntimeError as exc:
        return 1, [str(exc)]

    default_root = worktree_root or _default_worktree()
    if worktree_root is None and not yes:
        typed = ask_fn(f"Worktree root [{default_root}]: ").strip()
        if typed:
            default_root = typed
    root = Path(default_root)
    ok, projected, limit = worktree_budget(root)
    if not ok:
        return 1, [
            f"worktree root {root} projects paths to {projected} characters "
            f"(limit {limit}). Pick a shorter root such as {_default_worktree()}."
        ]
    try:
        root.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        return 1, [f"could not create worktree root {root}: {exc}"]

    pr_cfg: dict[str, Any] | None = None
    try:
        pr_cfg = _choose_pr(
            folder=folder,
            local_repo=local_repo,
            pr_repo=slug,
            enable_pr=enable_pr,
            yes=yes,
            ask=ask_fn,
            gh=gh or _gh_default,
        )
    except RuntimeError as exc:
        return 1, [str(exc)]

    windows = default_root if sys.platform == "win32" else r"C:\wt"
    other = default_root if sys.platform != "win32" else "/tmp/tf-wt"
    if sys.platform == "win32":
        windows = str(root)
    else:
        other = str(root)
    body = default_toml_text(windows=windows, other=other)
    if pr_cfg is not None:
        body += _PR_BLOCK.format(
            repo=pr_cfg["repo"],
            base=pr_cfg["base"],
            trusted=json.dumps(pr_cfg["trusted"]),
        )
    try:
        env_example.write_text(_ENV_EXAMPLE, encoding="utf-8")
        toml_path.write_text(body, encoding="utf-8")
    except OSError as exc:
        return 1, [f"write refused: {exc}"]
    notes.append(f"wrote {env_example.name}")
    notes.append(f"wrote {toml_path.name}")
    ignore_note = _ensure_gitignore(folder)
    if ignore_note:
        notes.append(ignore_note)
    if local_repo is not None:
        notes.append(f"default target repo: {local_repo} (pass --repo on each run)")
    if pr_cfg is not None:
        notes.append(f"PR mode on: {pr_cfg['repo']} base={pr_cfg['base']}")
    notes.append("Next:")
    notes.extend(f"  {line}" for line in _uv_lines())
    notes.extend(f"  {line}" for line in _activate_hint())
    notes.append("  set DEEPSEEK_API_KEY and TYPESAFE_API_KEY (see .env.example)")
    notes.append("  treefleet doctor")
    if install:
        installer = run_install or _run_install
        ok_install, message = installer(folder)
        notes.append(message)
        if not ok_install:
            return 1, notes
    return 0, notes


def _read_toml(path: Path) -> dict[str, Any]:
    if not path.is_file():
        raise ConfigError(f"{path.name} not found. Run treefleet init.")
    return tomllib.loads(path.read_text(encoding="utf-8"))


def _worktree_root_from_data(data: Mapping[str, Any], base: Path) -> Path:
    paths = data.get("paths")
    if not isinstance(paths, dict):
        raise ConfigError("treefleet.toml is missing [paths].")
    key = "worktree_windows" if sys.platform == "win32" else "worktree_other"
    return Path(str(paths.get(key, "")))


def run_doctor(
    *,
    cwd: Path | None = None,
    repo: Path | None = None,
    want_pr: bool = False,
    live: bool = False,
    as_json: bool = False,
    env: Mapping[str, str] | None = None,
    login: Callable[[Path], tuple[bool, str]] | None = None,
    models: Callable[[Path], tuple[bool, str]] | None = None,
    auth: Callable[[Mapping[str, str]], list[CheckRow]] | None = None,
    gh: Gh | None = None,
    interpreter: Callable[[Path, str], list[CheckRow]] | None = None,
) -> tuple[int, list[CheckRow]]:
    """Offline checks by default. Exit 1 when any red row appears. Yellow is ok."""
    found = env if env is not None else os.environ
    rows: list[CheckRow] = []

    major, minor = sys.version_info[:2]
    # Runtime guard: package metadata already requires >=3.12, but doctor still reports it.
    if major < 3 or (major == 3 and minor < 12):  # noqa: UP036
        rows.append(
            (
                False,
                f"red    Python {major}.{minor} < 3.12\n       fix: install Python 3.12+",
            )
        )
    else:
        rows.append((True, f"green  Python {major}.{minor}"))

    try:
        import treefleet as _tf  # noqa: F401

        rows.append((True, "green  treefleet importable"))
    except ImportError:
        rows.append(
            (
                False,
                "red    treefleet not importable\n"
                '       fix: activate .venv-orch or uv pip install -p .venv-orch -e ".[orchestrator,dev]"',
            )
        )

    # Explicit cwd (tests) keeps a folder-local toml; otherwise TREEFLEET_CONFIG / cwd default.
    toml_path = (cwd / "treefleet.toml") if cwd is not None else config_path()
    data: dict[str, Any] | None = None
    try:
        data = _read_toml(toml_path)
        rows.append((True, "green  treefleet.toml found"))
    except ConfigError as exc:
        rows.append((False, f"red    {exc}"))
        return _finish(rows, as_json)

    base = toml_path.parent
    raw_paths = data.get("paths")
    paths: dict[str, Any] = raw_paths if isinstance(raw_paths, dict) else {}
    orch_py = _python(base / str(paths.get("orchestrator_venv", ".venv-orch")))
    worker_py = _python(base / str(paths.get("worker_venv", ".venv-worker")))
    if orch_py.is_file():
        rows.append((True, f"green  orchestrator interpreter exists ({orch_py})"))
    else:
        rows.append(
            (
                False,
                f"red    orchestrator interpreter missing ({orch_py})\n"
                '       fix: uv venv .venv-orch && uv pip install -p .venv-orch -e ".[orchestrator,dev]"',
            )
        )
    if worker_py.is_file():
        rows.append((True, f"green  worker interpreter exists ({worker_py})"))
    else:
        rows.append(
            (
                False,
                f"red    worker interpreter missing ({worker_py})\n"
                '       fix: uv venv .venv-worker && uv pip install -p .venv-worker -e ".[worker]"',
            )
        )

    check_repo = repo if repo is not None else base
    interp = interpreter or interpreter_checks
    if worker_py.is_file():
        rows.extend(interp(check_repo, str(worker_py)))

    for key in ("DEEPSEEK_API_KEY", "TYPESAFE_API_KEY"):
        if found.get(key):
            rows.append((True, f"green  {key} is set"))
        else:
            rows.append((False, f"red    {key} is unset\n       fix: set {key}"))

    for _ok, text in env_differs(found, dotenv_values(base)):
        # Doctor: warning only. Process environment wins.
        rows.append((True, text.replace("red    ", "yellow ", 1)))

    cursor_name = "cursor-agent"
    cursor_block = data.get("cursor")
    if isinstance(cursor_block, dict) and cursor_block.get("cli"):
        cursor_name = str(cursor_block["cli"])
    cli = Path(cursor_name)
    logged, login_fix = (login or _default_login)(cli)
    if logged:
        rows.append((True, "green  cursor-agent is on PATH and logged in"))
    else:
        rows.append((False, f"red    cursor-agent is missing or not logged in\n       fix: {login_fix}"))
    listed, model_fix = (models or _default_models)(cli)
    if listed:
        rows.append((True, "green  cursor model list loads"))
    else:
        rows.append((False, f"red    cursor model list did not load\n       fix: {model_fix}"))

    try:
        wt = _worktree_root_from_data(data, base)
    except ConfigError as exc:
        rows.append((False, f"red    {exc}"))
        return _finish(rows, as_json)
    ok_budget, projected, limit = worktree_budget(wt)
    if not wt.exists():
        rows.append(
            (
                False,
                f"red    worktree root missing ({wt})\n       fix: mkdir {wt} (keep path under {limit} chars)",
            )
        )
    else:
        probe = wt / ".treefleet-doctor-write"
        try:
            probe.write_text("ok", encoding="utf-8")
            probe.unlink(missing_ok=True)
            writable = True
        except OSError:
            writable = False
        if not writable:
            rows.append((False, f"red    worktree root not writable ({wt})\n       fix: choose a writable short path"))
        elif not ok_budget:
            rows.append(
                (
                    False,
                    f"red    worktree root too long (projects to {projected}, limit {limit})\n"
                    f"       fix: use a shorter root such as {_default_worktree()}",
                )
            )
        else:
            rows.append((True, f"green  worktree root ok ({wt})"))

    pr_raw = data.get("pr")
    pr_enabled = isinstance(pr_raw, dict) and bool(pr_raw.get("enabled"))
    check_pr = want_pr or pr_enabled

    if repo is not None:
        err = validate_local_repo(repo)
        if err:
            rows.append((False, f"red    {err}\n       fix: pass a git repo with at least one commit"))
        else:
            rows.append((True, f"green  repo is a git repository ({repo})"))
            if _clean(repo):
                rows.append((True, "green  working tree is clean"))
            else:
                rows.append(
                    (
                        True,
                        f"yellow working tree is dirty (warning)\n"
                        f"       inspect: git -C {repo} status\n"
                        f"       optional: git -C {repo} stash\n"
                        "       nothing is deleted automatically",
                    )
                )
            stale = _stale(repo)
            if not stale:
                rows.append((True, "green  no stale worktrees"))
            else:
                listed = "\n".join(f"       inspect path: {path}" for path in stale[:8])
                rows.append(
                    (
                        True,
                        f"yellow {len(stale)} stale worktree(s) (warning)\n"
                        f"       inspect: git -C {repo} worktree list\n"
                        f"{listed}\n"
                        "       optional: git worktree remove <path>  (no --force)\n"
                        "       nothing is deleted automatically",
                    )
                )
            if check_pr and isinstance(pr_raw, dict) and pr_raw.get("base"):
                expected = str(pr_raw.get("base"))
                try:
                    branch = _current_branch(repo)
                except ValueError:
                    branch = ""
                if branch == expected:
                    rows.append((True, f"green  repo is on {expected}"))
                else:
                    rows.append(
                        (
                            False,
                            f"red    repo is on {branch or '(unknown)'}\n       fix: git -C {repo} checkout {expected}",
                        )
                    )

    if check_pr:
        try:
            settings = load_settings(toml_path)
        except MissingSecretError as exc:
            rows.append((False, f"red    {exc}"))
            return _finish(rows, as_json)
        except ConfigError as exc:
            rows.append((False, f"red    {exc}"))
            return _finish(rows, as_json)
        if not settings.pr.enabled and want_pr:
            rows.append((False, "red    pr is disabled\n       fix: set pr.enabled = true in treefleet.toml"))
        elif settings.pr.enabled:
            runner = gh or _gh_default
            try:
                from treefleet.pr.safety import urls_match

                remote = ""
                if repo is not None:
                    raw = subprocess.run(
                        ["git", "-C", str(repo), "remote", "get-url", "origin"],
                        capture_output=True,
                        text=True,
                        encoding="utf-8",
                        errors="replace",
                        timeout=30,
                        shell=False,
                        check=False,
                    )
                    remote = raw.stdout.strip()
                code, _out, _err = runner(["auth", "status"])
                if code != 0:
                    raise PreflightError("gh auth status failed")
                code, login_out, _err = runner(["api", "user", "--jq", ".login"])
                login_name = login_out.strip()
                if code != 0 or not login_name:
                    raise PreflightError("gh is not authenticated")
                code, perm_out, _err = runner(["api", f"repos/{settings.pr.repo}", "--jq", ".permissions.push"])
                if code != 0 or perm_out.strip().lower() not in {"true", "1"}:
                    raise PreflightError(f"no push permission on {settings.pr.repo}")
                if repo is not None and remote and not urls_match(remote, settings.pr.repo):
                    raise PreflightError("origin does not match pr.repo")
                code, _base_out, _err = runner(["api", f"repos/{settings.pr.repo}/branches/{settings.pr.base}"])
                if code != 0:
                    raise PreflightError(f"base branch {settings.pr.base} is not on {settings.pr.repo}")
                gh_smoke(settings.pr, runner)
                rows.append((True, "green  gh can read the pull request repo"))
                rows.append(trust_line(settings.pr, login_name))
            except PreflightError as exc:
                rows.append((False, f"red    {exc}"))

    if live:
        if auth is not None:
            rows.extend(auth(found))
        else:
            rows.extend(live_auth(found))

    return _finish(rows, as_json)


def _finish(rows: list[CheckRow], as_json: bool) -> tuple[int, list[CheckRow]]:
    if as_json:
        payload = [{"ok": ok, "text": text, "level": _level(text)} for ok, text in rows]
        print(json.dumps(payload, ensure_ascii=True))
    else:
        for _ok, text in rows:
            print(text)
    # Yellow warnings keep ok=True; only red fails.
    return (0 if all(ok for ok, _text in rows) else 1), rows


def _level(text: str) -> str:
    if text.startswith("red"):
        return "red"
    if text.startswith("yellow"):
        return "yellow"
    return "green"


def init_main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="treefleet init",
        epilog="Runs and doctor load treefleet.toml from TREEFLEET_CONFIG when set, else ./treefleet.toml.",
    )
    parser.add_argument("dir", nargs="?", default=".", help="TreeFleet project directory (default: .)")
    parser.add_argument("--yes", action="store_true", help="non-interactive defaults")
    parser.add_argument("--install", action="store_true", help="run the two uv venv installs")
    parser.add_argument("--repo", default=None, help="local path to the target git repo")
    parser.add_argument("--pr-repo", default=None, help="owner/name for [pr].repo")
    parser.add_argument("--enable-pr", action="store_true", default=False, help="write a [pr] block")
    parser.add_argument("--no-pr", action="store_true", default=False, help="skip PR mode")
    parser.add_argument("--worktree-root", default=None, help="short worktree root path")
    try:
        parsed = parser.parse_args(list(argv) if argv is not None else None)
    except SystemExit as exc:
        code = exc.code
        return 2 if code else 0
    if parsed.enable_pr and parsed.no_pr:
        print("use only one of --enable-pr / --no-pr", file=sys.stderr)
        return 2
    enable: bool | None = True if parsed.enable_pr else False if parsed.no_pr or parsed.yes else None
    code, notes = run_init(
        Path(parsed.dir),
        yes=parsed.yes,
        install=parsed.install,
        repo=parsed.repo,
        pr_repo=parsed.pr_repo,
        enable_pr=enable,
        worktree_root=parsed.worktree_root,
    )
    for note in notes:
        print(note)
    return code


def doctor_main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="treefleet doctor",
        epilog="Config path: TREEFLEET_CONFIG if set, else ./treefleet.toml.",
    )
    parser.add_argument("--repo", default=None, help="target git repo to inspect")
    parser.add_argument("--pr", action="store_true", help="run GitHub PR checks")
    parser.add_argument("--live", action="store_true", help="probe DeepSeek and TypeSafe auth")
    parser.add_argument("--json", action="store_true", help="machine-readable rows")
    try:
        parsed = parser.parse_args(list(argv) if argv is not None else None)
    except SystemExit as exc:
        code = exc.code
        return 2 if code else 0
    from treefleet.evals.harness import load_env

    load_env(Path.cwd())
    code, _rows = run_doctor(
        cwd=None,
        repo=Path(parsed.repo) if parsed.repo else None,
        want_pr=parsed.pr,
        live=parsed.live,
        as_json=parsed.json,
    )
    return code
